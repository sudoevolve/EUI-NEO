"""Generate the shared plot lookup tables from Matplotlib's _cm_listed.py.

Usage: python tools/generate_plot_colormaps.py /path/to/matplotlib/_cm_listed.py
No Matplotlib import or runtime dependency is required.
"""
import ast
import hashlib
from pathlib import Path
import sys

source = Path(sys.argv[1])
root = Path(__file__).resolve().parents[1]
tree = ast.parse(source.read_text(encoding="utf-8"))
tables = {}
for node in tree.body:
    if isinstance(node, ast.Assign):
        for target in node.targets:
            if isinstance(target, ast.Name) and target.id in ("_viridis_data", "_plasma_data", "_turbo_data"):
                tables[target.id] = ast.literal_eval(node.value)
lines = ["// Generated by tools/generate_plot_colormaps.py; do not edit table entries.",
         "// Source SHA256: " + hashlib.sha256(source.read_bytes()).hexdigest(),
         "// See licenses/plot-colormaps.txt for provenance and redistribution terms.",
         "#pragma once", "#include <array>", "namespace modules::plot::detail {"]
for name in ("viridis", "plasma", "turbo"):
    data = tables["_" + name + "_data"]
    assert len(data) == 256 and all(len(row) == 3 for row in data)
    lines.append("inline constexpr std::array<std::array<float, 3>, 256> " + name + " = {{")
    lines.extend("    {" + ", ".join(f"{v:.6f}f" for v in row) + "}," for row in data)
    lines.append("}};")
lines.append("} // namespace modules::plot::detail")
(root / "modules/plot/colormaps.h").write_text("\n".join(lines) + "\n", encoding="utf-8")
